#!/usr/bin/env python3
"""
Convert a 6x8 BDF font into a C file for the Genesis software text renderer.

Usage (run from the 68Katy directory):
    python3 fonts/bdf2c.py fonts/cp437-6x8.bdf > font_cp437_6x8.c

Output:
  font_6x8[256 * 8]
      One byte per glyph row, 8 rows per glyph. Only the low 6 bits are
      used: bit 5 = leftmost pixel, bit 0 = rightmost pixel.

  font_6x8_expand[64]
      Lookup table that turns one 6-bit glyph row into six 4bpp VDP pixels.
      The leftmost pixel lands in bits 23..20 and the rightmost in bits 3..0,
      and each lit pixel has colour index 1. hw_md.S shifts the result left
      or right to place the character anywhere inside an 8-pixel tile row.
"""
import sys

WIDTH, HEIGHT = 6, 8


def parse_bdf(path):
    glyphs = {}
    with open(path) as f:
        lines = [l.strip() for l in f]
    i = 0
    while i < len(lines):
        if lines[i].startswith("ENCODING"):
            code = int(lines[i].split()[1])
            while not lines[i].startswith("BBX"):
                i += 1
            w, h, xoff, yoff = (int(v) for v in lines[i].split()[1:5])
            if (w, h, xoff, yoff) != (WIDTH, HEIGHT, 0, 0):
                sys.exit("glyph %d: unexpected BBX %s" % (code, lines[i]))
            while lines[i] != "BITMAP":
                i += 1
            rows = [int(lines[i + 1 + r], 16) for r in range(HEIGHT)]
            for r in rows:
                if r & 0x03:
                    sys.exit("glyph %d: pixels outside 6-pixel width" % code)
            glyphs[code] = [r >> 2 for r in rows]
            i += HEIGHT
        i += 1
    if sorted(glyphs) != list(range(256)):
        sys.exit("expected exactly 256 glyphs (0-255), found %d" % len(glyphs))
    return glyphs


def expand(v):
    out = 0
    for p in range(WIDTH):
        if v & (1 << (WIDTH - 1 - p)):
            out |= 1 << (20 - 4 * p)
    return out


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: %s font.bdf > font.c" % sys.argv[0])
    glyphs = parse_bdf(sys.argv[1])
    out = sys.stdout
    out.write("/* Code Page 437 6x8 font for the Genesis software text renderer. */\n")
    out.write("/* GENERATED by fonts/bdf2c.py from fonts/cp437-6x8.bdf - do not edit. */\n\n")
    out.write("/* One byte per row, 8 rows per glyph; bit 5 = leftmost pixel. */\n")
    out.write("const unsigned char font_6x8[256 * 8] =\n{\n")
    for code in range(256):
        rows = ", ".join("0x%02X" % r for r in glyphs[code])
        out.write("\t%s,\t/* %02X */\n" % (rows, code))
    out.write("};\n\n")
    out.write("/* 6-bit glyph row -> six 4bpp pixels (colour 1) in bits 23..0. */\n")
    out.write("const unsigned long font_6x8_expand[64] =\n{\n")
    for v in range(0, 64, 4):
        vals = ", ".join("0x%08X" % expand(v + k) for k in range(4))
        out.write("\t%s,\n" % vals)
    out.write("};\n")


if __name__ == "__main__":
    main()
